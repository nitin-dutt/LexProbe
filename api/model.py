"""
Model runtime for the LexProbe API.

Loads the 4-bit base model + the v4 LoRA adapter once and exposes `analyze(text)`: full-document analysis
(src/inference.py) with the same prompt, chunking and first-token scoring used in training and evaluation.

Scoring modes (env SCORING):
  single (default) v6b alone, ONE pass per chunk: margin minus a per-clause prior shift, threshold from
                   configs/model_v6b.json (7 clauses, dataset profile v4; validation-selected, test scored once).
  blend            per-clause logistic blend of the v4 margin (adapter on) and the zero-shot margin (adapter off),
                   weights/threshold from configs/blend_v1.json (6 clauses, alignment_plan D7). Two passes per chunk.
  v4               v4 margin alone with DECISION_THRESHOLD (env, default 0); 6 clauses.
Evidence quotes are always generated by the fine-tuned adapter.

Heavy ML imports happen inside load_model(), so this module can be imported (and tested) without torch.
"""

import os
import sys
import threading

from dotenv import load_dotenv

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
if SRC not in sys.path:
    sys.path.insert(0, SRC)

load_dotenv()

SCORING = os.environ.get("SCORING", "single").lower()
if SCORING not in ("single", "blend", "v4"):
    raise ValueError(f"SCORING must be 'single', 'blend' or 'v4', got {SCORING!r}")
SINGLE_CONFIG = os.environ.get("SINGLE_CONFIG", os.path.join(ROOT, "configs", "model_v6b.json"))
BLEND_CONFIG = os.environ.get("BLEND_CONFIG", os.path.join(ROOT, "configs", "blend_v1.json"))

from single_model import load_single, single_scores  # noqa: E402

SINGLE = load_single(SINGLE_CONFIG) if SCORING == "single" else None
if SINGLE is not None:
    # The v6b config uses dataset profile v4 (7 clauses). This must be set before prepare_data is first imported.
    os.environ.setdefault("LEXPROBE_PROFILE", SINGLE["profile"])

from blend import blend_scores, load_blend  # noqa: E402
from inference import analyze_scored  # noqa: E402
from prepare_data import CLAUSE_TYPES  # noqa: E402
from prompting import NEGATIVE_ANSWER, POSITIVE_PREFIX, encode_prompt  # noqa: E402

if SINGLE is not None and set(SINGLE["clause_shift"]) != set(CLAUSE_TYPES):
    raise RuntimeError(
        f"config {SINGLE_CONFIG} is for clauses {sorted(SINGLE['clause_shift'])} but the process uses {sorted(CLAUSE_TYPES)}. "
        "Start the API with SCORING=single in a fresh process (LEXPROBE_PROFILE is picked from the config)."
    )

BASE_MODEL_ID    = "meta-llama/Llama-3.1-8B-Instruct"
ADAPTER_PATH     = os.environ.get("ADAPTER_PATH", SINGLE["adapter"] if SINGLE is not None else "models/llama-3.1-8b-cuad-lora-v4/final_adapter")
HF_TOKEN         = os.environ.get("HF_TOKEN")
MAX_QUOTE_TOKENS = 120
LOCK_TIMEOUT_S   = 120  # how long a request waits for the GPU before getting "busy"

if SCORING == "single":
    BLEND = None
    SCORING_MODE = SINGLE["name"]
    # Flag a clause when some chunk's shifted margin exceeds this value (chosen on validation, not 0).
    DECISION_THRESHOLD = float(SINGLE["threshold"])
elif SCORING == "blend":
    BLEND = load_blend(BLEND_CONFIG)
    SCORING_MODE = BLEND["name"]
    # Flag a clause when some chunk's blended score exceeds this value (fitted on validation, not 0).
    DECISION_THRESHOLD = float(BLEND["threshold"])
else:
    BLEND = None
    SCORING_MODE = "v4"
    # v4 alone: 0 = the model's natural boundary (high recall, more false alarms); see reports/eval/document_level.md.
    DECISION_THRESHOLD = float(os.environ.get("DECISION_THRESHOLD", "0.0"))

__all__ = ["CLAUSE_TYPES", "ADAPTER_PATH", "DECISION_THRESHOLD", "SCORING_MODE", "ModelBusyError", "load_model", "is_ready", "analyze"]


class ModelBusyError(RuntimeError):
    """The GPU is serving another request and the wait timed out."""


# Module-level singletons — loaded once on startup
_tokenizer = None
_model = None
_ids = {}
_gpu_lock = threading.Lock()  # one inference at a time on the 8 GB GPU (alignment_plan E3)


def load_model():
    """Load model + adapter into VRAM. Called once at API startup."""
    global _tokenizer, _model

    if _model is not None:
        return
    if not HF_TOKEN:
        raise RuntimeError("HF_TOKEN not set in environment / .env file.")

    import torch
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig

    print(f"[model] Loading base model {BASE_MODEL_ID} in 4-bit...")
    _tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL_ID, token=HF_TOKEN)
    base = AutoModelForCausalLM.from_pretrained(
        BASE_MODEL_ID,
        quantization_config=BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_use_double_quant=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.bfloat16,
        ),
        device_map="auto",
        token=HF_TOKEN,
    )

    print(f"[model] Applying LoRA adapter from {ADAPTER_PATH}...")
    model = PeftModel.from_pretrained(base, ADAPTER_PATH)
    model.eval()

    _ids.update({
        "found": _tokenizer(POSITIVE_PREFIX.strip(), add_special_tokens=False)["input_ids"][0],
        "none": _tokenizer(NEGATIVE_ANSWER, add_special_tokens=False)["input_ids"][0],
        "prefix": _tokenizer(POSITIVE_PREFIX.rstrip(), add_special_tokens=False)["input_ids"],
        "eot": [_tokenizer.convert_tokens_to_ids("<|eot_id|>"), _tokenizer.eos_token_id],
    })
    _model = model
    print(f"[model] Ready (scoring: {SCORING_MODE}, threshold {DECISION_THRESHOLD:+.2f}). VRAM in use: {torch.cuda.memory_allocated() / 1e9:.2f} GB")


def is_ready() -> bool:
    return _model is not None


def _score_chunk(chunk: str) -> dict:
    """{clause: score} for one chunk: the shifted v6b margin (single), the blended score, or the v4 margin alone."""
    from chunk_scoring import blend_chunk_margins, chunk_margins

    if SCORING == "blend":
        m_v4, m_base = blend_chunk_margins(_model, _tokenizer, _ids["found"], _ids["none"], chunk)
        return blend_scores(m_v4, m_base, BLEND)
    margins = chunk_margins(_model, _tokenizer, _ids["found"], _ids["none"], chunk)
    return single_scores(margins, SINGLE) if SCORING == "single" else margins


def _quote(clause_type: str, chunk: str) -> str:
    """Generate the evidence after a forced 'Found:' prefix (fine-tuned adapter enabled)."""
    import torch

    ids = encode_prompt(_tokenizer, clause_type, chunk) + _ids["prefix"]
    inp = torch.tensor([ids], device="cuda")
    with torch.no_grad():
        out = _model.generate(input_ids=inp, attention_mask=torch.ones_like(inp),
                              max_new_tokens=MAX_QUOTE_TOKENS, do_sample=False,
                              eos_token_id=_ids["eot"], pad_token_id=_tokenizer.eos_token_id)
    return _tokenizer.decode(out[0][len(ids):], skip_special_tokens=True)


def analyze(text: str) -> dict:
    """
    Full-document analysis. Returns
      {"contract_text": normalised text, "chunks_analyzed": int,
       "clauses": [{clause_type, detected, chunks_flagged, confidence_margin,
                    extracted_text, grounded, start, end, chunk_index}]}
    confidence_margin is the score that was compared with DECISION_THRESHOLD (blended score in blend mode).
    start/end are character offsets into contract_text.
    """
    if _model is None:
        raise RuntimeError("Model not loaded. Call load_model() first.")
    if not _gpu_lock.acquire(timeout=LOCK_TIMEOUT_S):
        raise ModelBusyError("The model is busy with another request. Please retry shortly.")
    try:
        return analyze_scored(text, _score_chunk, _quote, threshold=DECISION_THRESHOLD)
    finally:
        _gpu_lock.release()
